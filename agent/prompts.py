def build_system_prompt(tools: dict[str, Tool]) -> str:
    """组装系统提示词：人设 + 工作格式 + 动态工具清单 + 初始思维链 + 少样本。"""
    tool_lines = [
        f"- {name}：{tool.description}\n  参数：{tool.schema_text()}"
        for name, tool in tools.items()
    ]
    return "\n\n".join(
        [
            PERSONA,
            REACT_FORMAT,
            "## 可用工具\n" + "\n".join(tool_lines),
            INITIAL_COT,
            FEW_SHOT,
        ]
    )
